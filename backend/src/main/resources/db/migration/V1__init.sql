CREATE TABLE credit_application (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number      VARCHAR(20)   NOT NULL UNIQUE,
    applicant_name        VARCHAR(100)  NOT NULL,
    email                 VARCHAR(254)  NOT NULL,
    annual_income         NUMERIC(12,2) NOT NULL CHECK (annual_income >= 0),
    monthly_debt_payments NUMERIC(12,2) NOT NULL CHECK (monthly_debt_payments >= 0),
    credit_score          INTEGER       NOT NULL CHECK (credit_score BETWEEN 300 AND 900),
    requested_amount      NUMERIC(12,2) NOT NULL CHECK (requested_amount > 0),
    term_months           INTEGER       NOT NULL CHECK (term_months BETWEEN 6 AND 84),
    employment_status     VARCHAR(20)   NOT NULL,
    product_type          VARCHAR(20)   NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    risk_score            INTEGER       NOT NULL,
    dti_ratio             NUMERIC(6,4)  NOT NULL,
    apr                   NUMERIC(5,2)  NOT NULL,
    monthly_payment       NUMERIC(12,2) NOT NULL,
    approved_amount       NUMERIC(12,2),
    decided_by            VARCHAR(100)  NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    version               BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX idx_application_status_created ON credit_application (status, created_at);

CREATE TABLE application_reason_code (
    application_id BIGINT      NOT NULL REFERENCES credit_application (id) ON DELETE CASCADE,
    reason_code    VARCHAR(10) NOT NULL
);

CREATE INDEX idx_reason_application ON application_reason_code (application_id);

CREATE TABLE decision_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES credit_application (id),
    action         VARCHAR(20)  NOT NULL,
    from_status    VARCHAR(20),
    to_status      VARCHAR(20)  NOT NULL,
    actor          VARCHAR(100) NOT NULL,
    note           VARCHAR(500),
    rules_version  VARCHAR(20),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_application ON decision_audit (application_id);
